cv_scores = {}

for config in configs:
    print("\n" + "=" * 60)
    print("Configuration:", config["name"])
    print("=" * 60)

    fold_scores = []

    for fold, (train_idx, val_idx) in enumerate(
        skf.split(cv_paths, cv_labels),
        start=1
    ):
        print(f"\nFold {fold}/5")

        fold_train_paths = cv_paths[train_idx]
        fold_train_labels = cv_labels[train_idx]

        fold_val_paths = cv_paths[val_idx]
        fold_val_labels = cv_labels[val_idx]

        fold_train_ds = make_dataset(
            fold_train_paths,
            fold_train_labels,
            batch_size=config["batch_size"],
            shuffle=True
        )

        fold_val_ds = make_dataset(
            fold_val_paths,
            fold_val_labels,
            batch_size=config["batch_size"]
        )

        tf.keras.backend.clear_session()
        gc.collect()

        fold_model = build_feature_extractor_model(
            initializer=best_initializer,
            dropout_rate=config["dropout"]
        )

        if config["fine_tune"]:
            base = fold_model.layers[0]
            base.trainable = True

            fine_tune_at = len(base.layers) - 20

            for layer in base.layers[:fine_tune_at]:
                layer.trainable = False

            for layer in base.layers[fine_tune_at:]:
                if isinstance(layer, layers.BatchNormalization):
                    layer.trainable = False

        fold_model = compile_model(
            fold_model,
            optimizer=config["optimizer"],
            learning_rate=config["learning_rate"]
        )

        fold_model.fit(
            fold_train_ds,
            validation_data=fold_val_ds,
            epochs=CV_EPOCHS,
            verbose=0
        )

        _, fold_accuracy = fold_model.evaluate(
            fold_val_ds,
            verbose=0
        )

        fold_scores.append(fold_accuracy)

        print(f"Fold {fold} accuracy: {fold_accuracy:.4f}")

        del fold_model
        gc.collect()

    cv_scores[config["name"]] = fold_scores

