def build_feature_extractor_model(
    initializer="glorot",
    regularization=None,
    dropout_rate=0.0,
    batch_normalization=False
):
    base = MobileNetV2(
        input_shape=(224, 224, 3),
        include_top=False,
        weights="imagenet"
    )
    base.trainable = False

    if initializer == "zero":
        kernel_init = tf.keras.initializers.Zeros()
    elif initializer == "random":
        kernel_init = tf.keras.initializers.RandomNormal(
            mean=0.0, stddev=0.05
        )
    elif initializer == "glorot":
        kernel_init = tf.keras.initializers.GlorotUniform()
    elif initializer == "he":
        kernel_init = tf.keras.initializers.HeNormal()
    else:
        raise ValueError("Unknown initializer")

    kernel_regularizer = None
    if regularization == "l2":
        kernel_regularizer = regularizers.l2(1e-4)

    model_layers = [
        base,
        layers.GlobalAveragePooling2D(),
    ]

    if batch_normalization:
        model_layers.append(layers.BatchNormalization())

    model_layers.append(
        layers.Dense(
            128,
            activation="relu",
            kernel_initializer=kernel_init,
            kernel_regularizer=kernel_regularizer
        )
    )

    if dropout_rate > 0:
        model_layers.append(layers.Dropout(dropout_rate))

    model_layers.append(
        layers.Dense(
            NUM_CLASSES,
            activation="softmax",
            kernel_initializer=kernel_init
        )
    )

    model = models.Sequential(model_layers)

    return model


def compile_model(model, optimizer="adam", learning_rate=1e-3):
    if optimizer == "sgd":
        opt = tf.keras.optimizers.SGD(learning_rate=learning_rate)
    elif optimizer == "momentum":
        opt = tf.keras.optimizers.SGD(
            learning_rate=learning_rate,
            momentum=0.9
        )
    elif optimizer == "rmsprop":
        opt = tf.keras.optimizers.RMSprop(
            learning_rate=learning_rate
        )
    elif optimizer == "adam":
        opt = tf.keras.optimizers.Adam(
            learning_rate=learning_rate
        )
    else:
        raise ValueError("Unknown optimizer")

    model.compile(
        optimizer=opt,
        loss="sparse_categorical_crossentropy",
        metrics=["accuracy"]
    )

    return model


def plot_history(history, title, metric="loss"):
    plt.figure(figsize=(8, 5))

    if metric == "loss":
        plt.plot(history.history["loss"], label="Training Loss")
        plt.plot(history.history["val_loss"], label="Validation Loss")
        plt.ylabel("Loss")
    else:
        plt.plot(history.history["accuracy"], label="Training Accuracy")
        plt.plot(
            history.history["val_accuracy"],
            label="Validation Accuracy"
        )
        plt.ylabel("Accuracy")

    plt.xlabel("Epoch")
    plt.title(title)
    plt.legend()
    plt.grid(True)
    plt.show()


def make_dataset(paths, labels, batch_size=32, shuffle=False):
    ds = tf.data.Dataset.from_tensor_slices(
        (np.array([str(x) for x in paths]), np.array(labels))
    )
    ds = ds.map(
        load_image,
        num_parallel_calls=tf.data.AUTOTUNE
    )

    if shuffle:
        ds = ds.shuffle(1000)

    ds = ds.batch(batch_size).prefetch(tf.data.AUTOTUNE)

    return ds

